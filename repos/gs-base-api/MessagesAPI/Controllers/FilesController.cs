namespace MessagesAPI.Controllers
{
    /// <summary>
    /// To handle the files details.
    /// </summary>
    [ApiController]
    [Route("messagesapi")]
    public class FilesController : ControllerBase
    {
        private readonly ILogger<FilesController> _logger; // Good practice to inject logger
        private readonly static string configMessageFileFormat = AppConfiguration.Configuration["AppSettings:cm_message_file_format_not_supported"];
        private readonly static string configMessageFileTooHeavy = AppConfiguration.Configuration["AppSettings:cm_message_file_too_heavy"];
        private readonly static string connectionStringRead = AppConfiguration.Configuration["ConnectionStrings:EmailSystemManagerConnectionStringReader"];

        /// <summary>
        /// A post to upload files related to the messages (attachments). Be aware that you should send the header and body that are generated by the APIs, 
        /// or programs like Fiddler, to upload files. For example, Fiddler creates the content-type as multipart/formdata, and the request body included the details 
        /// of the internal files. So do not test this endpoint directly, unless you are using an API or application to upload files. This Content-Type is 
        /// different from the other calls that do not upload files, which are usually application/json but this one is autogenerated by those APIs.
        /// </summary>
        /// <param name="langCode">The user's interface language code. This has to be changed to the header in the future. Example: es for Spanish, en for English.</param>
        /// <returns> If the file was uploaded it returns a successful response.</returns>
        [HttpPost("files/upload/{langCode}")]
        public async Task<IActionResult> UploadFile([FromRoute] string langCode = "en")
        {
            string filePath = "";

            try
            {
                // Validate access token
                ValidationResponseModel responseSession = await GetUserDetails.GetUserIdRequestOnOtherAPI(
                    HttpContext, "MessagesAttach");
                if (!responseSession.SessionValid || string.IsNullOrWhiteSpace(responseSession.UserId))
                {
                    return Unauthorized();
                }

                // Get the file rules details
                var filesCache = new CustomClasses.CacheHandler.FilesCache();
                var attachmentRuleModels = filesCache.GetFileAttachmentRules();

                if (attachmentRuleModels == null || attachmentRuleModels.Count == 0)
                {
                    attachmentRuleModels = Files.GetEmailAttachmentRules();
                    _ = Task.Run(() => filesCache.SetFileAttachmentRules(attachmentRuleModels));
                }

                var formFiles = Request.Form.Files;
                if (formFiles == null || formFiles.Count == 0)
                {
                    return StatusCode(StatusCodes.Status415UnsupportedMediaType);
                }

                var file = formFiles[0];
                var fileName = file.FileName;
                var fileSize = file.Length;

                var extensionFile = Path.GetExtension(fileName)?.TrimStart('.').ToLower();
                var supportedFileModel = attachmentRuleModels.Find(x => x.FileType.ToLower() == extensionFile);

                if (supportedFileModel == null)
                {
                    var message = new MessageAPI.Services.EmailSystems.CustomClasses.MessageManager(
                        connectionStringRead,
                        langCode).GetMessageDetails(configMessageFileFormat);

                    return StatusCode(StatusCodes.Status415UnsupportedMediaType, new MessageAPI.Domain.Models.General.ResponseModel
                    {
                        SessionValid = false,
                        TransactionValid = false,
                        Messages = new List<string> { message }
                    });
                }

                if (fileSize > int.Parse(supportedFileModel.MaxSize))
                {
                    var message = new MessageAPI.Services.EmailSystems.CustomClasses.MessageManager(
                        connectionStringRead,
                        langCode).GetMessageDetails(configMessageFileTooHeavy);

                    return BadRequest(new MessageAPI.Domain.Models.General.ResponseModel
                    {
                        SessionValid = true,
                        TransactionValid = false,
                        Messages = new List<string> { message }
                    });
                }

                var newFileName = $"{Guid.NewGuid()}.{extensionFile}";
                object fileUrl = await AzureAssets.UploadFileToAzureStorage(file, newFileName);
                if (fileUrl == null)
                {
                    return StatusCode(StatusCodes.Status500InternalServerError);
                }
                // Else, return the file. 
                object fullFilePath = AzureAssets.GetFileFromAzureStorage(newFileName);
                return StatusCode(StatusCodes.Status201Created, new MessageAPI.Domain.Models.General.ResponseModel
                {
                    SessionValid = true,
                    TransactionValid = true,
                    Messages = new List<string> { fileUrl.ToString(), fullFilePath.ToString() }
                });
            }
            catch (Exception ex)
            {
                return BadRequest($"{ex} {filePath}");
            }
        }


        /// <summary>
        /// Returns the rules that apply to the files that are going to be upload.
        /// </summary>
        /// <returns>Returns the rules that applies to the files that are going to be upload.</returns>
        [HttpGet("files/rules")]
        public async Task<IActionResult> GetFileRules()
        {
            try
            {
                var filesCache = new CustomClasses.CacheHandler.FilesCache();
                var attachmentRuleModels = filesCache.GetFileAttachmentRules();

                if (attachmentRuleModels != null && attachmentRuleModels.Count > 0)
                {
                    return Ok(new AttachmentRuleResponseModel
                    {
                        TransactionValid = true,
                        SessionValid = true,
                        AttachmentRuleModelList = attachmentRuleModels
                    });
                }

                var responseSession = await GetUserDetails.GetUserIdRequestOnOtherAPI(HttpContext, "CommunicationMessage");
                if (!responseSession.SessionValid || string.IsNullOrWhiteSpace(responseSession.UserId))
                {
                    return Unauthorized();
                }

                attachmentRuleModels = Files.GetEmailAttachmentRules();

                _ = Task.Run(() => filesCache.SetFileAttachmentRules(attachmentRuleModels));

                return Ok(new AttachmentRuleResponseModel
                {
                    TransactionValid = true,
                    SessionValid = true,
                    AttachmentRuleModelList = attachmentRuleModels
                });
            }
            catch (Exception)
            {
                return BadRequest();
            }
        }
    }
}
