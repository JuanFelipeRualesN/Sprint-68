                            cmd.Parameters.AddWithValue("@code", lang.Code);
                        }
                        if (!string.IsNullOrEmpty(lang.Desc))
                        {
                            if (addAnd != true)
                            {
                                sql = string.Concat(sql, " where `desc` = @desc ");
                                addAnd = true;
                            }
                            else
                            {
                                sql = string.Concat(sql, " and `desc` = @desc ");
                            }
                            cmd.Parameters.AddWithValue("@desc", lang.Desc);
